from typing import Optional
from xml.etree import ElementTree as ET

MATHML_NAMESPACE: str = "http://www.w3.org/1998/Math/MathML"


def add_mathml_metadata(mathml_str: str, generator: str) -> str:
    """
    Adds the annotation "Generated by <generator>" to MathML using <semantics> and <annotation>.

    Args:
        mathml_str (str): The MathML content as a string.
        generator (str): Name of what created the MathML, for example "Paddle".

    Returns:
        The updated MathML string, or the input when it is not MathML.
    """
    try:
        root: ET.Element[str] = ET.fromstring(mathml_str)
    except ET.ParseError:
        return mathml_str

    if root.tag != f"{{{MATHML_NAMESPACE}}}math" and root.tag != "math":
        return mathml_str

    namespace: dict[str, str] = {"m": MATHML_NAMESPACE}
    ET.register_namespace("", MATHML_NAMESPACE)

    existing_semantics: Optional[ET.Element[str]] = root.find("m:semantics", namespace)
    if existing_semantics is not None:
        semantics: ET.Element[str] = existing_semantics
    else:
        # Move all children of <math> into <semantics>; semantics has one expression, so more children go into <mrow>
        semantics = ET.Element(f"{{{MATHML_NAMESPACE}}}semantics")
        children: list[ET.Element[str]] = list(root)
        expression: ET.Element[str] = semantics
        if len(children) > 1:
            expression = ET.SubElement(semantics, f"{{{MATHML_NAMESPACE}}}mrow")
        for child in children:
            expression.append(child)
            root.remove(child)
        root.append(semantics)

    text: str = f"Generated by {generator}"
    existing_texts: set[str] = {ann.text for ann in semantics.findall("m:annotation", namespace) if ann.text}
    if text not in existing_texts:
        annotation: ET.Element[str] = ET.SubElement(semantics, f"{{{MATHML_NAMESPACE}}}annotation")
        annotation.text = text
        annotation.set("encoding", "text/plain")

    return ET.tostring(root, encoding="unicode")
